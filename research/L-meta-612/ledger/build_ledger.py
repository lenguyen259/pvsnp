"""Build ledger.json and ledger.md from ledger_src.py + sanity_report.json + the circuit store.
Every witness circuit is re-verified on all 2^n inputs (dropped and reported if wrong).
Usage: python3 -I build_ledger.py
"""
import sys, os, json, gzip
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lib612 import *
from ledger_src import L

HERE = os.path.dirname(os.path.abspath(__file__))


def store_index():
    idx = {}
    for p in ("circuits.jsonl", "circuits_bulk.jsonl.gz"):
        for r in load_store([os.path.join(HERE, p)]):
            R = red(rec_circ(r))
            idx.setdefault(gkey(r["n"], r["edges"]) + "|" + R.to_str(), r["id"])
    return idx


def describe(cstr, idx):
    C = parse_str(cstr)
    E = graph_of_circuit(C)
    if E is None:
        return {"circuit": cstr, "error": "does not compute any f_G"}
    G = GraphCtx(C.n, E)
    R = red(C)
    cl = graph_class(C.n, E)
    return {"circuit": cstr, "n": C.n, "edges": [list(e) for e in G.E], "phi": G.phi, "tau": G.tau,
            "size": C.size, "n_and": C.n_and(), "n_or": C.n_or(), "slack": C.size - G.phi,
            "c4free": cl["c4free"], "subcubic": cl["subcubic"], "girth": cl["girth"], "pseudoforest": cl["pseudoforest"],
            "store_id": idx.get(gkey(C.n, E) + "|" + R.to_str()), "verified_all_inputs": True}


def estr(edges):
    return ",".join(("%d%d" % tuple(e)) if max(e) < 10 else "%d-%d" % tuple(e) for e in edges)


def main():
    idx = store_index()
    san = {}
    sp = os.path.join(HERE, "sanity_report.json")
    if os.path.exists(sp):
        S = json.load(open(sp))
        for r in S["results"]:
            san[r.get("ledger_id")] = r
    out = []
    problems = []
    for c in L:
        e = dict(c)
        e["scope"] = {"graphs": c["scope"][0], "circuits": c["scope"][1]}
        e["witnesses"] = []
        for w in c["wit"]:
            d = describe(w, idx)
            if "error" in d:
                problems.append((c["id"], w, d["error"]))
            e["witnesses"].append(d)
        del e["wit"]
        r = san.get(c["id"])
        if r is None and c["fz"]:
            r = next((x for x in san.values() if x["claim"] == c["fz"]), None)
        if r is not None:
            e["falsify"] = {"predicate": r["claim"], "in_scope": r["in_scope"], "checked": r["checked"],
                            "violations": r["violations"], "smallest": r["smallest"][:2]}
            if c["st"] == "REFUTED" and r["violations"] == 0:
                problems.append((c["id"], "falsify", "refuted claim not refuted by the store"))
            if c["st"] in ("PROVED", "LEAN", "DATA", "OPEN") and r["violations"] > 0:
                problems.append((c["id"], "falsify", "claim marked %s has store violations" % c["st"]))
        out.append(e)
    json.dump({"claims": out, "store": {"core": sum(1 for _ in open(os.path.join(HERE, "circuits.jsonl")))},
               "problems": problems}, open(os.path.join(HERE, "ledger.json"), "w"), indent=1)

    # ---------------------------------------------------------------- markdown
    st_order = ["OPEN", "DATA", "SAT", "LEAN", "PROVED", "REFUTED", "MOOT"]
    lab = {"OPEN": "Open", "DATA": "Open, machine evidence only (DATA)", "SAT": "SAT-verified base cases",
           "LEAN": "Proved in Lean", "PROVED": "Proved (hand proof)", "REFUTED": "Refuted", "MOOT": "Proved but superseded"}
    byid = {e["id"]: e for e in out}
    M = []
    M.append("# L-meta-612 claim ledger\n")
    M.append("Generated by `build_ledger.py` from `ledger_src.py`, `sanity_report.json` (falsify.py) and the circuit "
             "store. Every witness circuit below was re-checked on all 2^n inputs. Store ids `c......` are in "
             "`circuits.jsonl`, `b......` in `circuits_bulk.jsonl.gz`.\n")
    M.append("Status labels: **LEAN** (machine-checked proof), **PROVED** (hand proof in the cited file), **SAT** "
             "(solver UNSAT certificate), **DATA** (open; only machine evidence), **OPEN**, **REFUTED** "
             "(smallest known counterexample given), **MOOT** (proved, superseded). Scope = (graph class, circuit "
             "class); `reduced` = after functional reduction red (constants, duplicates, dead gates removed).\n")
    from collections import Counter
    cnt = Counter(e["st"] for e in out)
    M.append("Counts: " + ", ".join("%s %d" % (s, cnt[s]) for s in st_order if cnt[s]) + " (total %d).\n" % len(out))
    if problems:
        M.append("**Build problems:** " + "; ".join("%s: %s" % (p[0], p[2]) for p in problems) + "\n")

    M.append("## The path to MAIN-C3 (612 for C4-free graphs of maximum degree <= 3)\n")
    M.append("| role | claims |\n|---|---|")
    for role, name in [("goal", "goal"), ("proved-on-path", "proved, usable"), ("base-case", "base cases"),
                       ("open-on-path", "**OPEN on the path**"), ("dead-route", "dead routes (refuted)")]:
        ids = [e["id"] + (" (%s)" % e["st"]) for e in out if e["c3"] == role]
        M.append("| %s | %s |" % (name, ", ".join(ids)))
    M.append("")
    M.append("Open on the path, in the form needed: one of **T2** (deg3.md; with R-TOT on C3), **T2F**/**mANB** "
             "(with B options) or **E\\*opt**, for minimum circuits of a vertex-minimal "
             "counterexample of size Phi-1 (structure COR-M); plus the SAT base cases **SAT-H9**, **PET-EXACT** "
             "and the open 7-10 vertex graphs listed in subcubic.md. The split route (OR)+(AND) is dead on C3 "
             "(OR-C3 is refuted on an 8-vertex subcubic graph of girth 5), and so is every purely syntactic "
             "payment count (T2-LO, T2-LT, T2-LD, and now T2-LR, refuted on Petersen at Phi+2): a proof of T2 "
             "must count functional eliminations.\n")

    for s in st_order:
        es = [e for e in out if e["st"] == s]
        if not es:
            continue
        M.append("## %s\n" % lab[s])
        for e in es:
            M.append("### %s: %s\n" % (e["id"], e["title"]))
            M.append("- **Statement.** %s" % e["stmt"])
            M.append("- **Scope.** graphs: %s; circuits: %s" % (e["scope"]["graphs"], e["scope"]["circuits"]))
            M.append("- **Status.** %s. Source: `%s`." % (e["st"], e["where"]))
            if e["ev"]:
                M.append("- **Evidence / remark.** %s" % e["ev"])
            if e["uses"]:
                M.append("- **Uses.** " + ", ".join(e["uses"]))
            if e["implies"]:
                M.append("- **Implies.** " + ", ".join(e["implies"]))
            if e["c3"]:
                M.append("- **Role for MAIN-C3.** %s" % e["c3"])
            if "falsify" in e:
                f = e["falsify"]
                M.append("- **falsify.py `%s`.** %d in scope of %d store circuits, %d violations." %
                         (f["predicate"], f["in_scope"], f["checked"], f["violations"]))
                for w in f["smallest"][:1]:
                    M.append("  Smallest violation: n=%d, E=[%s], Phi=%d, size %d (#AND %d, #OR %d), store %s:  \n  `%s`" %
                             (w["n"], estr(w["edges"]), w["phi"], w["size"], w["n_and"], w["n_or"], w["id"], w["circuit"]))
            for w in e["witnesses"]:
                if "error" in w:
                    M.append("- **Witness (INVALID: %s).** `%s`" % (w["error"], w["circuit"]))
                    continue
                M.append("- **Witness.** n=%d, E=[%s], Phi=%d, size %d (#AND %d, #OR %d), girth %s, %s, store %s:  \n  `%s`" %
                         (w["n"], estr(w["edges"]), w["phi"], w["size"], w["n_and"], w["n_or"], w["girth"],
                          "subcubic" if w["subcubic"] else "max degree > 3", w["store_id"], w["circuit"]))
            M.append("")
    open(os.path.join(HERE, "ledger.md"), "w").write("\n".join(M) + "\n")
    print("claims", len(out), dict(cnt), "problems", problems)


if __name__ == "__main__":
    main()
