#!/usr/bin/env python3
"""Generator of Lean 4 lower-bound files for one-a-side bipartite mask instances.

    python3 gen.py N M MASK K out.lean MODULE [--with-upper] [--no-check]

writes `out.lean`, a file whose last theorem is `PEqualNP.Outside.<MODULE>`:

    not (PEqualNP.Represents.RepSizeAtMost
           (fun (u : Fin N) (v : Fin M) => (MASK : Nat).testBit (M * u.val + v.val)) K)

(no monotone AND/OR fan-in-2 circuit with at most K gates represents the graph).  It refuses (exit 2) when
such a circuit exists (the search finds it; the circuit is printed and re-checked with the Python mirror of
the Lean definitions), and exits 3 when the instance is degenerate.

Method (see README.md): live-set search of the accepted engine L_meta_6343 / L_meta_20635 (build, live,
compress, cuts, dispatch, optimized).  Wires are replaced by bit vectors over the |pos| x |neg| sample pairs;
the front check `inputs.sublists.all frontOK` is a kernel computation.  No own data types, no tables.
"""
import itertools
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from model import Inst, Search, unfolded_cost, represents, mono2, circ_eval, frontier  # noqa: E402
import tpl  # noqa: E402

FORBIDDEN = ['sorry', 'native_decide', 'macro', 'syntax', 'notation', 'elab', 'attribute', 'initialize',
             '"', '#']



BUDGET = 2000          # optimized calls per kernel chunk (about 0.6 MB each: the kernel keeps its caches)
MAX_FRONTIER = 60000   # states of the explicit frontier a chunk theorem recomputes


def start_sets(inst, K):
    out = []
    for r in range(0, min(inst.nw, K + 1) + 1):
        for sub in itertools.combinations(range(inst.nw), r):
            st = tuple(sorted(inst.inputs[i] for i in sub))
            if inst.cuts(st) == inst.full:
                out.append(sub)
    return out


def plan_start(inst, S, K, sub, cache):
    """Choose the frontier depth d and a chunk size c for one start set (mirror of the Lean fr / chunks)."""
    l = [inst.inputs[i] for i in sub]
    F0 = [(K + 1 - len(l), l)]
    best = None
    for d in range(0, K + 1):
        F = frontier(inst, F0, d)
        k0 = K - d
        costs = [unfolded_cost(S, k0, tuple(sorted(q[1])), cache) for q in F]
        mx = max(costs) if costs else 0
        if best is None or mx < best[0]:
            best = (mx, d, F, costs)
        if mx <= BUDGET or len(F) > MAX_FRONTIER:
            break
    mx, d, F, costs = best
    k0 = K - d
    # chunk size: largest c (by count) such that every chunk of c consecutive states costs <= BUDGET
    n = len(F)
    c = 1
    if n:
        lo, hi = 1, n
        def ok(c):
            return all(sum(costs[i:i + c]) <= max(BUDGET, mx) for i in range(0, n, c))
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if ok(mid):
                lo = mid
            else:
                hi = mid - 1
        c = lo
    m = (n + c - 1) // c
    return dict(sub=sub, d=d, k0=k0, c=c, m=max(m, 1), n=n, maxcost=mx, total=sum(costs))


def find_circuit(inst, K, S):
    """Return (gates, output) of a monotone circuit with <= K gates representing the graph, or None.
    gates: list of (op, [i, j]).  Mirrors exactly the start sets of the Lean front check."""
    nw = inst.nw
    for r in range(0, min(nw, K + 1) + 1):
        for sub in itertools.combinations(range(nw), r):
            st = tuple(sorted(inst.inputs[i] for i in sub))
            if inst.cuts(st) != inst.full:
                continue
            if S.solve(K, st):
                return extract(inst, K, S, st)
    return None


def extract(inst, K, S, st):
    wire = {v: j for j, v in enumerate(inst.inputs)}
    gates = []
    k = K
    cur = st
    while cur != (inst.goal,):
        ch, (op, a, b) = S.path[(k, cur)]
        w = (a & b) if op == 'and' else (a | b)
        gates.append((op, [wire[a], wire[b]]))
        wire[w] = inst.nw + len(gates) - 1
        cur, k = ch, k - 1
    return gates, wire[inst.goal]


def lean_hex(x):
    return '0x%x' % x


def fmt_cells(cells):
    return '[' + ', '.join('(%d, %d)' % c for c in cells) + ']'


def render(inst, K, module, cost, plans, upper=None):
    n, m, mask = inst.n, inst.m, inst.mask
    P, W = inst.P, inst.W
    sub = lambda t: t.replace('@W@', str(W)).replace('@P@', str(P))
    out = []
    out.append('import Mathlib\nimport PEqualNP.Defs\n')
    out.append('namespace PEqualNP.Outside.%s\n' % module)
    out.append('-- Generated by research/rep_lb/gen.py: graph %d x %d, mask %d, no circuit of size at most %d.' % (n, m, mask, K))
    out.append('-- The live-set engine (build, live, compress, cuts, dispatch, optimized, front replay) is the checked')
    out.append('-- file lean/PEqualNP/Outside/L_meta_6343.lean of this repository (Bastian Milan, PR 12547, Apache-2.0),')
    out.append('-- as reused in L_meta_20635; the widths, sample lists and bound are regenerated for this graph.')
    out.append('-- Search size: %d start sets, about %d optimized calls.\n' % (cost[0], cost[1]))
    out.append(sub(tpl.T1))
    out.append('def rawInputs : List W :=\n  [' + ', '.join(lean_hex(x) for x in inst.inputs) + ']\n')
    out.append(sub(tpl.T2))
    out.append(tpl.T3)
    out.append('\n')
    out.append('def A : Fin %d → Fin %d → Bool := fun (u : Fin %d) (v : Fin %d) => (%d : ℕ).testBit (%d * u.val + v.val)\n'
               % (n, m, n, m, mask, m))
    out.append('def posL : List (Fin %d × Fin %d) :=\n  %s\n' % (n, m, fmt_cells(inst.pos)))
    out.append('def negL : List (Fin %d × Fin %d) :=\n  %s\n' % (n, m, fmt_cells(inst.neg)))
    nneg = len(inst.neg)
    out.append('def samp (k : Fin %d) : Fin %d × Fin %d :=\n  if k.val < %d then negL.getD (k.val %% %d) (0, 0) else posL.getD ((k.val - %d) / %d) (0, 0)\n'
               % (W, n, m, P, nneg, P, nneg))
    t4 = sub(tpl.T4)
    t4 = t4.replace('Fin 5 × Fin 5', 'Fin %d × Fin %d' % (n, m))
    out.append(t4)
    out.append('\n')
    out.append(tpl.T5)
    out.append('\n')
    nsub = 1 << inst.nw
    chunks = (nsub + 1023) // 1024
    K1 = K + 1
    out.append('def pick (idx : List ℕ) : List W := idx.map (fun i => inputs.getD i 0)\n')
    out.append('def starts : List (List ℕ) :=\n  [%s]\n' % ', '.join('[' + ', '.join(map(str, p['sub'])) + ']' for p in plans))
    out.append('def frontOK (l : List W) : Bool :=\n  decide (%d < l.length) || cuts l != -1 || starts.any (fun s => pick s == l)\n' % K1)
    for j in range(chunks):
        out.append('set_option maxRecDepth 8000 in\nset_option maxHeartbeats 40000000 in\n'
                   'theorem all_front_%d : ((inputs.sublists.drop (1024 * %d)).take 1024).all frontOK = true := by\n  decide +kernel\n' % (j, j))
    out.append('theorem all_front : inputs.sublists.all frontOK = true :=\n'
               '  all_of_chunks frontOK 1024 %d inputs.sublists (by decide +kernel) (fun j hj => by\n'
               '    interval_cases j\n    exacts [%s])\n' % (chunks, ', '.join('all_front_%d' % j for j in range(chunks))))
    for i, p in enumerate(plans):
        d, k0, c, mm = p['d'], p['k0'], p['c'], p['m']
        out.append('def F%d : List (ℕ × List W) := [(%d - (pick starts[%d]!).length, pick starts[%d]!)]\n' % (i, K1, i, i))
        for j in range(mm):
            out.append('set_option maxRecDepth 8000 in\nset_option maxHeartbeats 40000000 in\n'
                       'theorem chunk%d_%d : (((fr %d F%d).drop (%d * %d)).take %d).all (fun q => !optimized %d q.1 q.2) = true := by\n  decide +kernel\n'
                       % (i, j, d, i, c, j, c, k0))
        out.append('set_option maxRecDepth 8000 in\nset_option maxHeartbeats 40000000 in\ntheorem allFalse%d : AllFalse %d (fr %d F%d) :=\n'
                   '  allFalse_of_all _ _ (all_of_chunks (fun q => !optimized %d q.1 q.2) %d %d (fr %d F%d) (by decide +kernel) (fun j hj => by\n'
                   '    interval_cases j\n    exacts [%s]))\n'
                   % (i, k0, d, i, k0, c, mm, d, i, ', '.join('chunk%d_%d' % (i, j) for j in range(mm))))
        out.append('set_option maxRecDepth 8000 in\nset_option maxHeartbeats 40000000 in\ntheorem start%d : optimized %d (%d - (pick starts[%d]!).length) (pick starts[%d]!) = false := by\n'
                   '  have hok : frOK %d F%d = true := by decide +kernel\n'
                   '  have h := fr_sound %d F%d %d hok allFalse%d\n'
                   '  exact h _ (List.mem_singleton_self _)\n' % (i, K, K1, i, i, d, i, d, i, k0, i))
    # starts_false: every start is covered
    body = 'fun _ h => absurd h List.not_mem_nil'
    for i in reversed(range(len(plans))):
        body = 'List.forall_mem_cons.2 ⟨start%d, %s⟩' % (i, body)
    out.append('theorem starts_false : ∀ s ∈ starts, optimized %d (%d - (pick s).length) (pick s) = false :=\n  %s\n' % (K, K1, body))
    G = 'PEqualNP.CircuitLowerBounds.'
    graph = '(fun (u : Fin %d) (v : Fin %d) => (%d : ℕ).testBit (%d * u.val + v.val))' % (n, m, mask, m)
    lower = 'fun h => Exists.elim h (fun C hC => PEqualNP.Outside.%s.no_small C hC.1 hC.2.1 hC.2.2)' % module
    if upper is None:
        upperdefs = ''
        stmt = '¬ PEqualNP.Represents.RepSizeAtMost %s %d :=\n  %s\n' % (graph, K, lower)
    else:
        gates, output = upper
        gl = ', '.join('{ op := %s%s, inputs := [%s] }' % (G + 'GateOp.', op, ', '.join(map(str, ins))) for op, ins in gates)
        alts = ' | '.join(['rfl'] * len(gates))
        upperdefs = (
            'def upperA : Fin %d → Fin %d → Bool := fun (u : Fin %d) (v : Fin %d) => (%d : ℕ).testBit (%d * u.val + v.val)\n\n'
            'def upperC : %sCircuit :=\n  { gates := [%s],\n    output := %d }\n\n'
            'theorem upper_mono : PEqualNP.MetaComplexity.Monotone2 upperC := by\n  intro g hg\n'
            '  simp only [upperC, List.mem_cons, List.not_mem_nil, or_false] at hg\n'
            '  rcases hg with %s <;> simp\n\n'
            'theorem upper_rep : PEqualNP.Represents.Represents upperA upperC := by\n  decide +kernel\n\n'
            % (n, m, n, m, mask, m, G, gl, output, alts))
        stmt = ('PEqualNP.Represents.RepSizeAtMost %s %d ∧ ¬ PEqualNP.Represents.RepSizeAtMost %s %d :=\n'
                '  ⟨⟨PEqualNP.Outside.%s.upperC, PEqualNP.Outside.%s.upper_mono, by decide, PEqualNP.Outside.%s.upper_rep⟩,\n   %s⟩\n'
                % (graph, K + 1, graph, K, module, module, module, lower))
    out.append('''theorem no_small (C : Circuit) (hm : Monotone2 C) (hs : C.size ≤ %(K)d)
    (hr : PEqualNP.Represents.Represents A C) : False := by
  obtain ⟨S, hsub, hl⟩ := compress (get_build C hm hr)
  have hlK : live basicOps goal %(K)d S := extend_live hs hl
  let l := inputs.filter (fun w => decide (w ∈ S))
  have hlS : l.toFinset = S := by
    ext v
    simp only [l, List.mem_toFinset, List.mem_filter, decide_eq_true_eq]
    constructor
    · exact fun h => h.2
    · exact fun h => ⟨List.mem_toFinset.mp (hsub h), h⟩
  have hnd : l.Nodup := inputs_nodup.filter _
  have hlive : live basicOps goal %(K)d l.toFinset := hlS ▸ hlK
  have hcard := live_card hlive
  rw [List.toFinset_card_of_nodup hnd] at hcard
  have hsearch := optimized_complete %(K)d l (%(K1)d - l.length) hnd (by omega) hlive
  have hcut : cuts l = -1 := cuts_full hlive
  have hmem : l ∈ inputs.sublists := List.mem_sublists.mpr List.filter_sublist
  have hrow := List.all_eq_true.mp all_front l hmem
  have h4 : decide (%(K1)d < l.length) = false := by simp; omega
  have h5 : (cuts l != -1) = false := by simp [hcut]
  simp only [frontOK] at hrow
  rw [h4, h5] at hrow
  simp only [Bool.false_or, List.any_eq_true, beq_iff_eq] at hrow
  obtain ⟨s, hs2, hsl⟩ := hrow
  have hf := starts_false s hs2
  rw [hsl] at hf
  rw [hf] at hsearch
  exact Bool.false_ne_true hsearch
''' % dict(K=K, K1=K1))
    out.append('''%(upperdefs)send PEqualNP.Outside.%(mod)s

theorem PEqualNP.Outside.%(mod)s : %(stmt)s
''' % dict(mod=module, upperdefs=upperdefs, stmt=stmt))
    return '\n'.join(out)


def check_rules(text, module):
    """CONTRIBUTING rules that can be checked textually (see README)."""
    problems = []
    lines = text.split('\n')
    if lines[0] != 'import Mathlib' or lines[1] != 'import PEqualNP.Defs':
        problems.append('import lines')
    body = '\n'.join(lines[2:])
    if re.search(r'\bimport\b', body):
        problems.append('the word import after the import lines')
    low = body
    for w in FORBIDDEN:
        if w in low:
            problems.append('forbidden token %r' % w)
    for mo in re.finditer(r'^set_option (\S+) (\S+) in$', body, re.M):
        if mo.group(1) not in ('maxRecDepth', 'maxHeartbeats', 'synthInstance.maxSize', 'synthInstance.maxHeartbeats'):
            problems.append('option ' + mo.group(1))
    n_opts = len(re.findall(r'set_option', body))
    n_good = len(re.findall(r'^set_option (maxRecDepth|maxHeartbeats|synthInstance\.maxSize|synthInstance\.maxHeartbeats) \d+ in$', body, re.M))
    if n_opts != n_good:
        problems.append('malformed set_option')
    if len(re.findall(r'^theorem PEqualNP\.Outside\.%s\b' % module, text, re.M)) != 1:
        problems.append('final theorem')
    last_thm = [l for l in lines if l.startswith('theorem ')][-1]
    if not last_thm.startswith('theorem PEqualNP.Outside.%s ' % module):
        problems.append('final theorem is not last')
    for num in re.findall(r'\b\d+\b', text):
        if len(num) > 20:
            problems.append('long numeral')
    if len(text.encode()) > 512 * 1024:
        problems.append('file too large')
    return problems


def main(argv):
    args = [a for a in argv if not a.startswith('--')]
    flags = [a for a in argv if a.startswith('--')]
    if len(args) != 6:
        print(__doc__)
        return 1
    n, m, mask, K = (int(x) for x in args[:4])
    out, module = args[4], args[5]
    if n < 2 or m < 2 or mask < 0 or mask >= 1 << (n * m) or K < 0:
        print('degenerate or out-of-range instance (need N, M >= 2, 0 <= MASK < 2^(N*M), K >= 0)')
        return 3
    inst = Inst(n, m, mask)
    if not inst.pos or not inst.neg:
        print('degenerate: the graph is empty or complete (repSize 0 or 1); no lower bound to prove for K >= 1')
        return 3
    if len(set(inst.inputs)) != inst.nw:
        print('degenerate: two input wires carry the same sample word; the engine needs distinct inputs')
        return 3
    S = Search(inst)
    circ = find_circuit(inst, K, S)
    if circ is not None:
        gates, output = circ
        ok = mono2(gates) and len(gates) <= K and represents(n, m, mask, gates, output)
        print('REFUSED: a monotone circuit with %d <= %d gates represents the graph (Python mirror check: %s)'
              % (len(gates), K, ok))
        print('gates', gates, 'output', output)
        return 2
    # kernel work estimate: number of optimized calls without any memo, as Lean does it
    cache = {}
    tot, starts = 0, 0
    for r in range(0, min(inst.nw, K + 1) + 1):
        for sub in itertools.combinations(range(inst.nw), r):
            st = tuple(sorted(inst.inputs[i] for i in sub))
            if inst.cuts(st) != inst.full:
                continue
            starts += 1
            tot += unfolded_cost(S, K, st, cache)
    upper = None
    if '--with-upper' in flags:
        upper = find_circuit(inst, K + 1, S)
        if upper is None:
            print('REFUSED (--with-upper): no circuit with %d gates found, the value is above %d' % (K + 1, K + 1))
            return 2
        g2, o2 = upper
        assert mono2(g2) and len(g2) <= K + 1 and represents(n, m, mask, g2, o2)
    plans = [plan_start(inst, S, K, sub, {}) for sub in start_sets(inst, K)]
    text = render(inst, K, module, (starts, tot), plans, upper)
    problems = check_rules(text, module)
    if problems and '--no-check' not in flags:
        print('rule check failed:', problems)
        return 4
    with open(out, 'w') as f:
        f.write(text)
    print('OK: no circuit of size <= %d. P=%d width=%d, %d start sets with full cuts, ~%d optimized calls, %d bytes -> %s'
          % (K, inst.P, inst.W, starts, tot, len(text.encode()), out))
    for p in plans:
        print('  start %s: depth %d, frontier %d states, chunk %d x %d, max chunk cost ~%d' % (p['sub'], p['d'], p['n'], p['c'], p['m'], p['maxcost']))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
